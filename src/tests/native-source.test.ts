import assert from 'node:assert/strict';
import source from '../../tests/fixtures/native-6.0.6/source-before.json';
import expected from '../../tests/fixtures/native-6.0.6/expected.json';
import { decodeActor606, decodeItem606, documentIdentity, ownedItemUuid, deepFreeze } from '../logic/native/6.0.6/source';
import { itemSummary } from '../logic/content/projection';

const frozen = deepFreeze(structuredClone(source));
const untouched = structuredClone(source);
const actor = decodeActor606(frozen);
assert.equal(actor.uuid, expected.decode.actorUuid);
assert.equal(actor.capability, 'character-target');
assert.equal(actor.items.fixtureSpell0001.identity.uuid, expected.decode.firstSpellUuid);
assert.equal(decodeActor606({ ...source, type: 'vehicle' }).capability, 'read-only-unsupported-automation');
assert.equal(decodeActor606({ ...source, type: 'npc' }).capability, 'linked-npc-target-read-only');
const first = decodeItem606(frozen.items[1], ownedItemUuid(source._id, frozen.items[1]._id));
assert.equal(first.identity.uuid, expected.decode.firstSpellUuid);
assert.equal(first.provenance.compendiumSource, expected.decode.firstSpellSourceUuid);
assert.equal(first.edition, expected.decode.firstSpellEdition);
assert.notEqual(first.source, frozen.items[1]);
assert.ok(Object.isFrozen(first.source));
const second = decodeItem606(frozen.items[2], ownedItemUuid(source._id, frozen.items[2]._id));
assert.equal(second.edition, expected.decode.secondSpellEdition);
assert.notEqual(first.identity.uuid, second.identity.uuid);
const fromArray = decodeItem606(frozen.items[0], ownedItemUuid(source._id, frozen.items[0]._id));
assert.deepEqual(Object.keys(fromArray.advancements), expected.decode.advancementIds);
const objectSource = structuredClone(source.items[0]);
Object.assign(objectSource.system, { advancement: fromArray.advancements });
const fromObject = decodeItem606(objectSource, ownedItemUuid(source._id, objectSource._id));
assert.deepEqual(fromObject.advancements, fromArray.advancements);
const duplicate = structuredClone(source.items[0]);
duplicate.system.advancement!.push(structuredClone(duplicate.system.advancement![0]));
assert.ok(decodeItem606(duplicate, fromArray.identity.uuid).diagnostics.some(d => d.code === 'duplicate-embedded-identity'));
const unknown = structuredClone(source.items[1]);
unknown.system.activities!.fixtureAct000001.type = 'arbitrary-custom-hook';
assert.ok(decodeItem606(unknown, first.identity.uuid).diagnostics.some(d => d.code === 'unsupported-type'));
assert.throws(() => decodeItem606(source.items[1], second.identity.uuid), /Invalid Item identity/);
assert.equal(documentIdentity('Duplicate name'), null);
assert.equal(documentIdentity('Compendium.example.options.fixtureSpell0001'), null);
const noEdition = { _id: 'noEdition', name: 'Modern-looking label', type: 'spell', system: {} };
assert.equal(decodeItem606(noEdition, 'Compendium.dnd5e.spells24.Item.noEdition').edition, 'unknown');
const hidden = { ...structuredClone(source.items[1]), name: 'SECRET TRUE NAME', system: { ...source.items[1].system,
    identified: false, unidentified: { name: 'Unknown scroll', description: 'SECRET UNRENDERED TEXT' }, description: { value: 'SECRET TRUE DESCRIPTION' } } };
const summary = itemSummary(hidden, first.identity.uuid);
assert.equal(summary.name, 'Unknown scroll');
assert.equal(summary.provenance, null);
assert.doesNotMatch(JSON.stringify(summary), /SECRET|Compendium.example/);
assert.deepEqual(frozen, untouched, 'nested extension/effect/ownership/source data deeply unchanged');
console.log('R/S: detached 6.0.6 schemas/identity/projection: PASS (no native runtime)');
